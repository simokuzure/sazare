with eligible_errors as (
    select answer_error.*
    from user_answer_errors answer_error
    inner join user_answers user_answer
        on user_answer.id = answer_error.user_answer_id
       and user_answer.deleted = false
    inner join questions question
        on question.id = answer_error.question_id
       and question.enabled = true
       and question.deleted = false
    where answer_error.user_error_type_id is not null
), inserted_cards as (
    insert into review_cards (
        user_id,
        user_error_type_id,
        status,
        ease_factor,
        repetition_count,
        interval_days,
        lapse_count,
        due_at,
        last_reviewed_at,
        mastered_at,
        created_at,
        updated_at
    )
    select
        user_error_type.user_id,
        user_error_type.id,
        'ACTIVE',
        2.5000,
        0,
        1,
        0,
        (max(answer_error.created_at)::date + 1) + time '07:00',
        null,
        null,
        current_timestamp,
        current_timestamp
    from user_error_types user_error_type
    inner join eligible_errors answer_error
        on answer_error.user_error_type_id = user_error_type.id
    where user_error_type.status = 'ACTIVE'
    group by user_error_type.id, user_error_type.user_id
    on conflict (user_error_type_id) do nothing
    returning id, user_error_type_id
), inserted_cycles as (
    insert into review_cycles (
        review_card_id,
        cycle_no,
        status,
        target_success_count,
        successful_review_count,
        failed_review_count,
        verification_required_after,
        started_at,
        completed_at,
        created_at,
        updated_at
    )
    select
        inserted_card.id,
        1,
        'IN_PROGRESS',
        4,
        0,
        0,
        max(answer_error.created_at),
        current_timestamp,
        null,
        current_timestamp,
        current_timestamp
    from inserted_cards inserted_card
    inner join eligible_errors answer_error
        on answer_error.user_error_type_id = inserted_card.user_error_type_id
    group by inserted_card.id
    returning id, review_card_id
), source_questions as (
    select
        answer_error.user_error_type_id,
        answer_error.question_id,
        min(answer_error.created_at) as first_error_at
    from eligible_errors answer_error
    group by answer_error.user_error_type_id, answer_error.question_id
)
insert into review_cycle_questions (
    review_cycle_id,
    question_id,
    question_role,
    review_status,
    attempt_count,
    last_quality,
    last_attempt_at,
    passed_at,
    sort_order,
    created_at,
    updated_at
)
select
    inserted_cycle.id,
    source_question.question_id,
    'ORIGINAL',
    'PENDING',
    0,
    null,
    null,
    null,
    (row_number() over (
        partition by inserted_cycle.id
        order by source_question.first_error_at, source_question.question_id
    ) - 1)::integer,
    current_timestamp,
    current_timestamp
from inserted_cycles inserted_cycle
inner join inserted_cards inserted_card
    on inserted_card.id = inserted_cycle.review_card_id
inner join source_questions source_question
    on source_question.user_error_type_id = inserted_card.user_error_type_id
on conflict (review_cycle_id, question_id) do nothing;

