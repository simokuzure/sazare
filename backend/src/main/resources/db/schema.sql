create table if not exists tags (
    id bigint generated by default as identity primary key,
    tag_type varchar(32) not null,
    parent_id bigint null,
    code varchar(64) not null,
    name varchar(64) not null,
    description varchar(255) null,
    sort_order integer not null default 0,
    enabled boolean not null default true,
    deleted boolean not null default false,
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp,

    constraint uq_tags_code unique (code),
    constraint ck_tags_type check (tag_type in ('SCENE', 'FUNCTION', 'GENRE')),
    constraint ck_tags_parent_not_self check (parent_id is null or parent_id <> id)
);

comment on table tags is '标签表';
comment on column tags.id is '主键ID';
alter table tags drop constraint if exists ck_tags_type;
alter table tags
    add constraint ck_tags_type
    check (tag_type in ('SCENE', 'FUNCTION', 'GENRE'));

comment on column tags.tag_type is '标签类型：SCENE=场景标签，FUNCTION=功能标签，GENRE=文章体裁标签';
comment on column tags.parent_id is '父标签ID，用于一级、二级标签层级关系，由代码维护有效性';
comment on column tags.code is '标签编码，供后端和AI稳定识别使用';
comment on column tags.name is '标签中文名称';
comment on column tags.description is '标签说明';
comment on column tags.sort_order is '排序值，数值越小越靠前';
comment on column tags.enabled is '是否启用';
comment on column tags.deleted is '是否删除';
comment on column tags.created_at is '创建时间';
comment on column tags.updated_at is '更新时间';

create index if not exists idx_tags_type on tags (tag_type);
create index if not exists idx_tags_parent_id on tags (parent_id);
create index if not exists idx_tags_enabled_deleted on tags (enabled, deleted);

create table if not exists question_tags (
    id bigint generated by default as identity primary key,
    question_id bigint not null,
    tag_id bigint not null,
    created_at timestamp not null default current_timestamp,

    constraint uq_question_tags_question_id_tag_id unique (question_id, tag_id)
);

comment on table question_tags is '题目标签关联表';
comment on column question_tags.id is '主键ID';
comment on column question_tags.question_id is '题目ID，对应 questions.id，由代码维护有效性';
comment on column question_tags.tag_id is '标签ID，对应 tags.id，由代码维护有效性';
comment on column question_tags.created_at is '创建时间';

create index if not exists idx_question_tags_question_id on question_tags (question_id);
create index if not exists idx_question_tags_tag_id on question_tags (tag_id);

